// Shows a neutral cream block (never a wrong photo) if the file is missing.
export function SmartImage({ src, alt, className = "", priority = false }) {
  const [failed, setFailed] = useState(false);

  if (!src || failed) {
    return <div role="img" aria-label={alt} className={`bg-[#F3EBE1] ${className}`} />;
  }
  return (
    <img
      src={src}
      alt={alt}
      loading={priority ? "eager" : "lazy"}
      onError={() => setFailed(true)}
      className={`object-cover ${className}`}
    />
  );
}